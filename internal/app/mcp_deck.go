func (a *deckAutomation) schema(topic string) any {
	types := map[string]reflect.Type{"action": reflect.TypeFor[nativeEditorAction](), "element": reflect.TypeFor[Element](), "slide": reflect.TypeFor[Slide](), "activity": reflect.TypeFor[EngagementDefinition](), "table": reflect.TypeFor[TableData](), "chart": reflect.TypeFor[ChartData](), "theme": reflect.TypeFor[DeckTheme](), "build": reflect.TypeFor[SlideBuild]()}
	if typ, ok := types[topic]; ok {
		return automationTypeSchema(typ)
	}
	switch topic {
	case "commands":
		names := strings.Fields(automationCommands)
		sort.Strings(names)
		return map[string]any{
			"commands":    names,
			"conventions": "Zero-based indices. Select the slide first; contextual commands use its selection. Native action geometry and element.query left/top/width/height use authored grid cells, NOT scene pixels. Inspected scene bounds use physical pixels. Omitted slide defaults to the current slide/master. add-slide without name creates a blank slide; named presets: title, section, body, columns, quote, comparison. Text query uses render=truetype, modern-font=c64/sans/mono (or a font ID), modern-size and modern-width. Use set-selection-property for styles/effects and set-selection-geometry for grid-space bounds. Preserve inspected fields when updating elements or slide appearance. add-element text accepts elementData; configure other kinds after insertion using update-element. IDs are generated by the native editor. select-elements accepts objectIds; duplicate-element/delete-element/move-element default to the selected element when element is omitted.",
			"grid":        map[string]int{"columns": authoredTerminalWidth, "rows": authoredTerminalHeight},
			"workflow":    []string{"deck_inspect", "deck_schema(action/element/properties)", "editor_command(select-slide)", "editor_command(add-element/update-element/set-selection-property)", "slide_screenshot", "deck_validate", "deck_save"},
		}
	case "properties":
		effects := map[string]any{}
		for property, c := range effectControls {
			effects[property] = map[string]any{"metadata": c.key, "default": c.fallback, "max": c.max, "choices": c.choices}
		}
		return map[string]any{"keys": selectionPropertyIDs, "effects": effects, "selection": a.editor.state().SelectionCapabilities, "note": "set-selection-property uses property, propertyValue and objectIds. Property values are typed: numbers, booleans or strings; empty string restores inheritance where supported."}
	case "templates":
		return presentationTemplateCatalog
	case "fonts":
		a.editor.mu.RLock()
		fonts := mergeTypefaces(a.editor.deck.Typefaces, a.editor.fontLibrary)
		a.editor.mu.RUnlock()
		return map[string]any{"bundled": map[string]string{"c64": "Keynope C64", "sans": "Go", "mono": "Go Mono"}, "deck": redactAutomationData(fonts), "import": "Use font_import with a workspace TTF/OTF file, then use the returned ID as modern-font. Native embedding and preview-only restrictions apply."}
	case "activities":
		catalog := activityDesignJS
		if at := strings.Index(catalog, "// Every activity"); at >= 0 {
			catalog = catalog[:at]
		}
		items := []map[string]string{}
		for _, match := range regexp.MustCompile(`(?m)^    ([a-z]+):\['([^']+)'`).FindAllStringSubmatch(catalog, -1) {
			items = append(items, map[string]string{"kind": match[1], "title": match[2]})
		}
		sort.Slice(items, func(i, j int) bool { return items[i]["title"] < items[j]["title"] })
		return map[string]any{"activities": items, "schema": automationTypeSchema(reflect.TypeFor[EngagementDefinition]()), "example": EngagementDefinition{Kind: "pulse", Prompt: "How confident are we?", Options: defaultPulseOptions, TimerSeconds: 120}, "note": "Configure using set-engagement. Running, participant chat and live phase controls remain presenter-owned; importing a deck never starts a workshop."}
	case "shapes":
		var catalog any
		_ = json.Unmarshal([]byte(shapeCatalogJSON()), &catalog)
		return catalog
	default:
		return map[string]any{"topics": []string{"commands", "action", "element", "slide", "activity", "activities", "table", "chart", "theme", "build", "properties", "templates", "shapes", "fonts"}}
	}
}

func (a *deckAutomation) snapshot() (Deck, string, int64) {
	s := a.editor
	s.mu.RLock()
	defer s.mu.RUnlock()
	return cloneDeckForRender(s.deck), s.deckPath, s.version
}

func automationSlide(deck Deck, input automationArguments) (Slide, Slide, error) {
	cols, rows := authoredRenderSize(245, 56)
	if input.Master {
		if input.Slide < 0 || input.Slide > len(deck.Masters.Layouts) {
			return Slide{}, Slide{}, errors.New("master index out of range (0=base, 1 onward=layouts)")
		}
		return *masterSlideAt(&deck, input.Slide), deck.masterRenderPreview(input.Slide, cols, rows), nil
	}
	if input.Slide < 0 || input.Slide >= len(deck.Slides) {
		return Slide{}, Slide{}, errors.New("slide index out of range")
	}
	return deck.Slides[input.Slide], deck.slideRenderPreview(input.Slide, cols, rows), nil
}
func (a *deckAutomation) inspect() map[string]any {
	s := a.editor
	s.mu.RLock()
	defer s.mu.RUnlock()
	slides := make([]map[string]any, len(s.deck.Slides))
	for i, slide := range s.deck.Slides {
		title := ""
		for _, e := range slide.Elements {
			if e.Text != "" {
				title = strings.Split(e.Text, "\n")[0]
				if len(title) > 200 {
					title = title[:200]
				}
				break
			}
		}
		slides[i] = map[string]any{"index": i, "id": slide.ID, "title": title, "elements": len(slide.Elements), "layout": slide.LayoutID, "tab": slide.TabID, "activity": slide.Engagement}
	}
	assets := map[string]any{}
	for id, asset := range s.deck.Assets {
		assets[id] = map[string]any{"mime": asset.MIME, "width": asset.Width, "height": asset.Height, "frames": len(asset.Frames)}
	}
	fonts := mergeTypefaces(s.deck.Typefaces, s.fontLibrary)
	return map[string]any{"version": s.version, "owner": s.notesSessionID, "path": s.deckPath, "dirty": s.dirtyLocked(), "current_slide": s.current, "current_master": s.currentMaster, "selected_element": s.selected, "master_mode": s.masterMode, "masters": redactAutomationData(s.deck.Masters), "slides": slides, "assets": assets, "fonts": redactAutomationData(fonts), "canvas": s.deck.physicalCanvas(), "grid": map[string]int{"columns": authoredTerminalWidth, "rows": authoredTerminalHeight}, "undo": len(s.undo), "redo": len(s.redo), "workspace": a.directory, "attached": a.attached}
}
func redactAutomationData(value any) any {
	raw, _ := json.Marshal(value)
	var root any
	_ = json.Unmarshal(raw, &root)
	var visit func(any) any
	visit = func(v any) any {
		switch v := v.(type) {
		case map[string]any:
			for k, child := range v {
				if k == "data" || k == "frames" || k == "typefaces" || k == "emojiFonts" {
					delete(v, k)
				} else {
					v[k] = visit(child)
				}
			}
		case []any:
			for i, child := range v {
				v[i] = visit(child)
			}
		case string:
			if strings.HasPrefix(v, "data:") && len(v) > 200 {
				return "[embedded resource]"
			}
		}
		return v
	}
	return visit(root)
}
func (a *deckAutomation) checkVersion(expected *int64) error {
	if expected == nil {
		return errors.New("expected_version is required; inspect the deck first")
	}
	a.editor.mu.RLock()
	version := a.editor.version
	a.editor.mu.RUnlock()
	if *expected != version {
		return fmt.Errorf("stale deck revision: expected %d, current %d; inspect again", *expected, version)
	}
	return nil
}
func (a *deckAutomation) checkImagePaths(elements []Element) error {
	for _, e := range elements {
		if e.Kind != "image" || e.AssetID != "" || e.Path == "" {
			continue
		}
		path, err := a.relative(e.Path)
		if err != nil {
			return err
		}
		f, err := a.root.Open(path)
		if err != nil {
			return fmt.Errorf("image must be embedded or inside workspace: %w", err)
		}
		info, err := f.Stat()
		f.Close()
		if err != nil || !info.Mode().IsRegular() {
			return errors.New("image is not a regular file")
		}
	}
	return nil
}
func (a *deckAutomation) command(ctx context.Context, raw json.RawMessage, version int64) error {
	var action nativeEditorAction
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&action); err != nil {
		return err
	}
	if !strings.Contains(" "+automationCommands+" ", " "+action.Action+" ") {
		return fmt.Errorf("unsupported automation command %q; use deck_schema(commands)", action.Action)
	}
	if err := a.checkImagePaths(action.ElementsData); err != nil {
		return err
	}
	if action.ElementData != nil {
		if err := a.checkImagePaths([]Element{*action.ElementData}); err != nil {
			return err
		}
	}
	if action.SlideData != nil {
		if err := a.checkImagePaths(action.SlideData.Elements); err != nil {
			return err
		}
	}
	if action.Clipboard != nil {
		if err := a.checkImagePaths(action.Clipboard.Elements); err != nil {
			return err
		}
	}
	state := a.editor.state()
	if state.Version != version {
		return errors.New("the deck changed; inspect before editing")
	}
	if action.Action == "select-elements" && len(action.ElementsData) == 0 {
		a.editor.mu.RLock()
		var elements []Element
		if state.MasterMode {
			elements = masterSlideAt(&a.editor.deck, state.Current).Elements
		} else if state.Current >= 0 && state.Current < len(a.editor.deck.Slides) {
			elements = a.editor.deck.Slides[state.Current].Elements
		}
		if len(action.ObjectIDs) > 0 {
			action.ElementIndices = nil
			for _, id := range action.ObjectIDs {
				found := -1
				for i, e := range elements {
					if e.ID == id {
						if found >= 0 {
							a.editor.mu.RUnlock()
							return errors.New("ambiguous object ID")
						}
						found = i
					}
				}
				if found < 0 {
					a.editor.mu.RUnlock()
					return fmt.Errorf("object %q not found in current slide/master", id)
				}
				action.ElementIndices = append(action.ElementIndices, found)
			}
		}
		for _, index := range action.ElementIndices {
			if index < 0 || index >= len(elements) {
				a.editor.mu.RUnlock()
				return errors.New("element index out of range")
			}
			action.ElementsData = append(action.ElementsData, Element{ID: elements[index].ID})
		}
		a.editor.mu.RUnlock()
	}
	action.SceneRevision = &version
	action.automationRevision = &version
	action.NotesSessionID = state.NotesSessionID
	action.SceneMaster = state.MasterMode
	var fields map[string]json.RawMessage
	_ = json.Unmarshal(raw, &fields)
	if _, explicit := fields["slide"]; !explicit {
		action.Slide = state.Current
	}
	if _, explicit := fields["element"]; !explicit && state.Selected >= 0 {
		switch action.Action {
		case "duplicate-element", "delete-element", "move-element", "convert-text-kind":
			action.Element = state.Selected
		}
	}
	action.commandContext = ctx
	if action.TypefaceData != nil {
		prepared, err := prepareTypeface(*action.TypefaceData)
		if err != nil {
			return err
		}
		action.TypefaceData = &prepared
	}
	return a.editor.apply(action)
}

func (a *deckAutomation) call(ctx context.Context, name string, input automationArguments) (map[string]any, []byte, error) {
	switch name {
	case "deck_inspect":
		return a.inspect(), nil, nil
	case "emoji_catalog":
		limit := input.Limit
		if limit == 0 {
			limit = 40
		}
		if input.Offset < 0 || input.Offset > 100000 || limit < 1 || limit > 100 {
			return nil, nil, errors.New("offset must be 0–100000; limit must be 1–100")
		}
		items := []map[string]string{}
		for _, entry := range emojiCatalogSearch(input.Query, input.Group, input.Offset, limit) {
			items = append(items, map[string]string{"emoji": entry.Emoji, "name": entry.Name, "group": entry.Group})
		}
		more := len(items) == limit && len(emojiCatalogSearch(input.Query, input.Group, input.Offset+limit, 1)) > 0
		return map[string]any{"items": items, "groups": emojiCatalogGroups(), "more": more, "next_offset": input.Offset + len(items)}, nil, nil
	case "font_export_review":
		if !validFontExportFormat(input.Format) {
			return nil, nil, errors.New("invalid font export format")
		}
		deck, _, version := a.snapshot()
		fonts, err := restrictedExportFonts(deck, input.Format)
		if err != nil {
			return nil, nil, err
		}
		return map[string]any{"version": version, "format": input.Format, "fonts": fonts, "confirmation_required": len(fonts) > 0, "warning": "These fonts cannot be embedded. Other devices use an installed copy or fall back to a default font. Ask the user to accept references or choose replacements, then call font_export_confirm."}, nil, nil
	case "fonts_installed":
		limit := input.Limit
		if limit == 0 {
			limit = 40
		}
		if input.Offset < 0 || limit < 1 || limit > 100 {
			return nil, nil, errors.New("offset must be non-negative; limit must be 1–100")
		}
		raw, err := captureAutomation(ctx, "", 0, 1280, "fonts")
		if err != nil {
			return nil, nil, err
		}
		var entries []map[string]string
		if err = json.Unmarshal(raw, &entries); err != nil {
			return nil, nil, err
		}
		filtered := []map[string]string{}
		query := strings.ToLower(input.Query)
		for _, entry := range entries {
			if strings.Contains(strings.ToLower(entry["name"]+" "+entry["postScriptName"]), query) {
				filtered = append(filtered, entry)
			}
		}
		start := min(input.Offset, len(filtered))
		end := min(start+limit, len(filtered))
		return map[string]any{"fonts": filtered[start:end], "total": len(filtered), "more": end < len(filtered), "next_offset": end}, nil, nil
	case "editor_state":
		state := a.editor.state()
		if input.IncludeData {
			raw, _ := json.Marshal(state)
			var result map[string]any
			_ = json.Unmarshal(raw, &result)
			return result, nil, nil
		}
		return redactAutomationData(state).(map[string]any), nil, nil
	case "selection_copy":
		state := a.editor.state()
		if state.SelectionCapabilities == nil || len(state.SelectionCapabilities.TargetIDs) == 0 {
			return nil, nil, errors.New("select objects before copying")
		}
		raw, _ := json.Marshal(map[string]any{"version": state.Version, "ids": state.SelectionCapabilities.TargetIDs})
		result, err := automationHTTP(ctx, a.editor.handleObjectClipboard, raw)
		return map[string]any{"version": state.Version, "clipboard": result}, nil, err
	case "editor_preview":
		if err := a.checkVersion(input.ExpectedVersion); err != nil {
			return nil, nil, err
		}
		handlers := map[string]http.HandlerFunc{"text": a.editor.handlePreview, "shape": a.editor.handleShapeDraft, "shape-adjustment": a.editor.handleShapeAdjustmentDraft, "connector": a.editor.handleConnectorDraft, "connector-route": a.editor.handleConnectorPreview, "media": a.editor.handleMediaDraft, "table": a.editor.handleTableDraft, "table-cell-style": a.editor.handleTableCellStyleDraft, "text-style": a.editor.handleTextStyleDraft, "fit-text": a.editor.handleFitText, "text-kind": a.editor.handleNormalizeTextKind}
		handler := handlers[input.Topic]
		if handler == nil {
			return nil, nil, errors.New("unknown preview topic")
		}
		var fields map[string]json.RawMessage
		if err := json.Unmarshal(input.Command, &fields); err != nil {
			return nil, nil, err
		}
		state := a.editor.state()
		fields["sceneRevision"], _ = json.Marshal(state.Version)
		fields["notesSessionId"], _ = json.Marshal(state.NotesSessionID)
		fields["sceneMaster"], _ = json.Marshal(state.MasterMode)
		if fields["slide"] == nil {
			fields["slide"], _ = json.Marshal(state.Current)
		}
		raw, _ := json.Marshal(fields)
		var action nativeEditorAction
		if err := json.Unmarshal(raw, &action); err != nil {
			return nil, nil, err
		}
		if err := a.checkImagePaths(action.ElementsData); err != nil {
			return nil, nil, err
		}
		if action.ElementData != nil {
			if err := a.checkImagePaths([]Element{*action.ElementData}); err != nil {
				return nil, nil, err
			}
		}
		result, err := automationHTTP(ctx, handler, raw)
		return map[string]any{"version": state.Version, "preview": result}, nil, err
	case "deck_schema":
		return map[string]any{"topic": input.Topic, "schema": a.schema(input.Topic)}, nil, nil
	case "slide_inspect":
		deck, _, version := a.snapshot()
		authored, resolved, err := automationSlide(deck, input)
		if err != nil {
			return nil, nil, err
		}
		if resolved.ModernScene == nil {
			return nil, nil, errors.New("could not project slide/master; inspect deck validation diagnostics")
		}
		result := map[string]any{"version": version, "master": input.Master, "authored": authored, "resolved": resolved, "scene": resolved.ModernScene}
		if !input.IncludeData {
			return redactAutomationData(result).(map[string]any), nil, nil
		}
		return result, nil, nil
	case "deck_validate":
		deck, _, version := a.snapshot()
		if err := validateDeckPlacementQueries(deck); err != nil {
			return nil, nil, err
		}
		if err := validateObjectReferenceScopes(deck); err != nil {
			return nil, nil, err
		}
		cols, rows := authoredRenderSize(245, 56)
		var issues []any
		for i := range deck.Slides {
			if err := ctx.Err(); err != nil {
				return nil, nil, err
			}
			scene, err := buildStyledSceneTargetMeasured(deck, deck.ResolveSlide(i, false), i, cols, rows, true, "", nil)
			if err != nil {
				return nil, nil, fmt.Errorf("slide %d: %w", i, err)
			}
			if len(scene.Diagnostics) > 0 {
				issues = append(issues, map[string]any{"slide": i, "diagnostics": scene.Diagnostics})
			}
		}
		return map[string]any{"version": version, "valid": true, "render_diagnostics": issues, "note": "Structural/render validation; visually inspect screenshots for text overflow and unintended overlap."}, nil, nil
	case "slide_screenshot":
		if input.Path != "" && !strings.EqualFold(filepath.Ext(input.Path), ".png") {
			return nil, nil, errors.New("screenshot destination must end in .png")
		}
		deck, path, version := a.snapshot()
		if input.Page < 0 {
			return nil, nil, errors.New("page out of range")
		}
		// A private screenshot is not a distributed font export. Embedded preview-
		// only text remains uneditable through the normal mutation checks.
		cols, rows := authoredRenderSize(245, 56)
		_, slide, err := automationSlide(deck, input)
		if err != nil {
			return nil, nil, err
		}
		if slide.ModernScene == nil {
			return nil, nil, errors.New("could not project the slide for native rendering; inspect render diagnostics")
		}
		slide.TabID = ""
		document, err := exportHTMLDocument(path, []Slide{slide}, cols, rows, preservedExportHead{}, false)
		if err != nil {
			return nil, nil, err
		}
		width := input.Width
		if width == 0 {
			width = 1280
		}
		if width < 320 || width > 2048 {
			return nil, nil, errors.New("screenshot width must be 320–2048")
		}
		image, err := captureAutomation(ctx, document, input.Page, width, "png")
		if err != nil {
			return nil, nil, err
		}
		result := map[string]any{"version": version, "slide": input.Slide, "master": input.Master, "page": input.Page, "mime": "image/png"}
		if input.Path != "" {
			saved, err := a.write(input.Path, image, input.Overwrite)
			if err != nil {
				return nil, nil, err
			}
			result["path"] = saved
		}
		return result, image, nil
	}
	if err := a.checkVersion(input.ExpectedVersion); err != nil {
		return nil, nil, err
	}
	switch name {
	case "editor_command":
		if err := a.command(ctx, input.Command, *input.ExpectedVersion); err != nil {
			return nil, nil, err
		}
	case "editor_batch":
		if len(input.Commands) < 1 || len(input.Commands) > 64 {
			return nil, nil, errors.New("batch needs 1–64 commands")
		}
		version := *input.ExpectedVersion
		for i, raw := range input.Commands {
			if err := ctx.Err(); err != nil {
				return nil, nil, err
			}
			if err := a.command(ctx, raw, version); err != nil {
				return nil, nil, fmt.Errorf("batch stopped after %d applied commands: %w", i, err)
			}
			a.editor.mu.RLock()
			next := a.editor.version
			a.editor.mu.RUnlock()
			if next > version+1 {
				return nil, nil, fmt.Errorf("batch stopped after %d commands: another editor changed the deck", i+1)
			}
			version = next
		}
	case "deck_new", "deck_open":
		if a.attached {
			return nil, nil, errors.New("use File/New or File/Open in the Mac app to replace its native document; isolated MCP workspaces support this tool")
		}
		if a.editor.state().Dirty && !input.Discard {
			return nil, nil, errors.New("unsaved work: save first or explicitly set discard_unsaved")
		}
		var deck Deck
		var err error
		path := filepath.Join(a.directory, "Untitled.md")
		if name == "deck_new" {
			if input.Template != "" {
				deck, err = loadPresentationTemplate(input.Template)
			} else {
				deck, err = loadPresentationTemplate("blank")
			}
		} else {
			relative, pathErr := a.relative(input.Path)
			if pathErr != nil {
				return nil, nil, pathErr
			}
			path = filepath.Join(a.directory, relative)
			data, readErr := a.read(input.Path, 128<<20)
			if readErr != nil {
				return nil, nil, readErr
			}
			if strings.EqualFold(filepath.Ext(path), ".pptx") {
				deck, _, err = importPPTXDocument(data, path)
			} else {
				deck, err = parseDeckDataWithAssetPublication(path, data, false)
			}
			if err == nil {
				for _, slide := range append(deck.Slides, deck.Masters.Base.Slide) {
					if err = a.checkImagePaths(slide.Elements); err != nil {
						break
					}
				}
				for _, layout := range deck.Masters.Layouts {
					if err != nil {
						break
					}
					err = a.checkImagePaths(layout.Slide.Elements)
				}
			}
		}
		if err != nil {
			return nil, nil, err
		}
		if len(deck.Slides) == 0 {
			return nil, nil, errors.New("deck has no slides")
		}
		materializeDeckAssets(&deck)
		previous := a.editor.version
		a.editor = newNativeEditorSession(path, deck, name == "deck_new")
		a.editor.version = previous + 1
	case "video_import":
		data, err := a.read(input.Path, maxEmbeddedVideoBytes)
		if err != nil {
			return nil, nil, err
		}
		id, asset, path, err := embeddedVideoAsset(ctx, data, nil)
		if err != nil {
			return nil, nil, err
		}
		a.editor.mu.RLock()
		element := videoElement(id, path, asset, &a.editor.deck)
		a.editor.mu.RUnlock()
		version := *input.ExpectedVersion
		state := a.editor.state()
		if err = a.editor.apply(nativeEditorAction{Action: "add-element", Kind: "video", ElementData: &element, AssetData: &asset, SceneRevision: &version, automationRevision: &version, SceneMaster: state.MasterMode, Slide: state.Current, NotesSessionID: state.NotesSessionID, uploadContext: ctx}); err != nil {
			return nil, nil, err
		}
	case "asset_import":
		data, err := a.read(input.Path, 50<<20)
		if err != nil {
			return nil, nil, err
		}
		id, asset, path, err := embeddedImageAssetContext(ctx, data)
		if err != nil {
			return nil, nil, err
		}
		version := *input.ExpectedVersion
		state := a.editor.state()
		element := Element{Kind: "image", AssetID: id, Path: path, Query: "image-style=modern"}
		if err = a.editor.apply(nativeEditorAction{Action: "add-element", Kind: "image", ElementData: &element, AssetData: &asset, SceneRevision: &version, automationRevision: &version, SceneMaster: state.MasterMode, Slide: state.Current, NotesSessionID: state.NotesSessionID, uploadContext: ctx}); err != nil {
			return nil, nil, err
		}
	case "font_export_confirm":
		state := a.editor.state()
		data, _ := json.Marshal(fontExportApproval{Owner: state.NotesSessionID, Version: *input.ExpectedVersion, Format: input.Format, Confirmed: input.Confirmed, Replacements: input.Replacements})
		_, err := automationHTTP(ctx, a.editor.handleFontExport, data)
		if err != nil {
			return nil, nil, err
		}
	case "font_import", "font_use_installed":
		var value DeckTypeface
		if name == "font_use_installed" {
			data, err := captureAutomation(ctx, input.Font, 0, 1280, "font")
			if err != nil {
				return nil, nil, err
			}
			if err = json.Unmarshal(data, &value); err != nil {
				return nil, nil, err
			}
		} else {
			data, err := a.read(input.Path, maxTypefaceBytes)
			if err != nil {
				return nil, nil, err
			}
			value = DeckTypeface{Name: strings.TrimSuffix(filepath.Base(input.Path), filepath.Ext(input.Path)), Data: data}
		}
		face, err := prepareTypeface(value)
		if err != nil {
			return nil, nil, err
		}
		version := *input.ExpectedVersion
		state := a.editor.state()
		if err = a.editor.apply(nativeEditorAction{Action: "register-typeface", TypefaceData: &face, NotesSessionID: state.NotesSessionID, automationRevision: &version}); err != nil {
			return nil, nil, err
		}
		result := a.inspect()
		result["font_id"] = face.ID()
		return result, nil, nil
	case "deck_save", "deck_export":
		format := input.Format
		if name == "deck_save" {
			format = "save"
		}
		ext := strings.ToLower(filepath.Ext(input.Path))
		required := map[string]string{"save": ".md", "html": ".html", "pptx": ".pptx", "pdf": ".pdf"}[format]
		if required == "" || ext != required && !(format == "save" && ext == ".markdown") {
			return nil, nil, fmt.Errorf("destination extension must match the %s format", format)
		}
		deck, source, err := a.editor.deckForFontExport(format)
		if err != nil {
			return nil, nil, err
		}
		var data []byte
		var report any
		cols, rows := authoredRenderSize(245, 56)
		switch format {
		case "save":
			data, err = serializeDeck(input.Path, deck)
		case "html":
			var content string
			content, err = exportHTMLDocument(source, deck.ResolvedSlides(), cols, rows, preservedExportHead{}, false)
			data = []byte(content)
		case "pptx":
			data, report, err = exportPPTXDocumentWithWork(deck, newPPTXExportWork(ctx))
		case "pdf":
			var content string
			content, err = exportHTMLDocument(source, deck.ResolvedSlides(), cols, rows, preservedExportHead{}, false)
			if err == nil {
				data, err = captureAutomation(ctx, content, 0, 1280, "pdf")
			}
		default:
			return nil, nil, errors.New("format must be html, pptx or pdf")
		}
		if err != nil {
			return nil, nil, err
		}
		saved, err := a.write(input.Path, data, input.Overwrite)
		if err != nil {
			return nil, nil, err
		}
		if format == "save" {
			if !a.editor.confirmSaved(saved, *input.ExpectedVersion) {
				return nil, nil, errors.New("saved snapshot, but document changed while saving; inspect and save the latest revision")
			}
		}
		result := a.inspect()
		result["output"] = saved
		result["bytes"] = len(data)
		result["conversion_report"] = report
		return result, nil, nil
	default:
		return nil, nil, errors.New("unknown tool")
	}
	result := a.inspect()
	result["selection"] = a.editor.state().SelectionCapabilities
	return result, nil, nil
}

// Reuse the native read-only API handlers without a loopback request, cookies,
// an HTTP test server or an alternate implementation of preview/clipboard math.
type automationResponse struct {
	header    http.Header
	body      bytes.Buffer
	status    int
	oversized bool
}

func (w *automationResponse) Header() http.Header { return w.header }
func (w *automationResponse) WriteHeader(status int) {
	if w.status == 0 {
		w.status = status
	}
}
func (w *automationResponse) Write(data []byte) (int, error) {
	if w.body.Len()+len(data) > 8<<20 {
		w.oversized = true
		return 0, errors.New("preview exceeds 8 MiB")
	}
	if w.status == 0 {
		w.status = 200
	}
	return w.body.Write(data)
}
func automationHTTP(ctx context.Context, handler http.HandlerFunc, body []byte) (any, error) {
	request, err := http.NewRequestWithContext(ctx, http.MethodPost, "http://127.0.0.1/", bytes.NewReader(body))
	if err != nil {
		return nil, err
	}
	request.Header.Set("Content-Type", "application/json")
	response := &automationResponse{header: make(http.Header)}
	handler(response, request)
	if response.oversized {
		return nil, errors.New("preview/clipboard exceeds 8 MiB; select fewer objects")
	}
	if response.status >= 400 {
		return nil, fmt.Errorf("native editor: %s", strings.TrimSpace(response.body.String()))
	}
	var result any
	if err = json.Unmarshal(response.body.Bytes(), &result); err != nil {
		return nil, err
	}
	return result, nil
}
